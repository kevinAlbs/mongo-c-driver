/*
 * Unified test runner for the async Rust-based C driver.
 *
 * Runs JSON tests from the MongoDB unified test format (schemaVersion 1.x)
 * using the async driver (Rust FFI) instead of the sync mongoc driver.
 *
 * Limitations / skips:
 *  - expectEvents: commandStartedEvent is checked; succeeded/failed ignored
 *  - No session support
 *  - No transactions, change streams, GridFS, aggregate, bulkWrite
 *  - No findOneAndDelete/Update/Replace
 *  - No index management
 *  - Operations with hint, sort, let, projection, limit, skip, collation,
 *    arrayFilters, bypassDocumentValidation, or upsert:true are skipped
 *  - Pipeline updates (array form) are skipped
 *  - testRunner operations (failPoint, etc.) cause the whole test to be skipped
 */

