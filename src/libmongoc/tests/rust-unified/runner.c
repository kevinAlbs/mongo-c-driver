/* -----------------------------------------------------------------------
 * Collection-level bulkWrite: dispatch each model as an individual operation.
 *
 * Only single-request bulkWrite is supported; multi-request is skipped to
 * avoid expectEvents mismatches (we would send N separate commands instead of
 * one batched command).
 * ----------------------------------------------------------------------- */

static op_status_t
run_bulk_write (mongoc_async_collection_t *coll,
                const bson_t *args,
                mongoc_async_error_t **out_err,
                char **skip_reason)
{
   /* Parse the 'requests' array. */
   bson_iter_t ri;
   if (!bson_iter_init_find (&ri, args, "requests") ||
       !BSON_ITER_HOLDS_ARRAY (&ri)) {
      fprintf (stderr, "[rust-unified] bulkWrite: missing 'requests'\n");
      return OP_FAIL;
   }
   uint32_t rl;
   const uint8_t *rd;
   bson_iter_array (&ri, &rl, &rd);
   bson_t reqs_arr;
   bson_init_static (&reqs_arr, rd, rl);

   /* Count requests. */
   bson_iter_t ci;
   bson_iter_init (&ci, &reqs_arr);
   int n_reqs = 0;
   while (bson_iter_next (&ci)) {
      n_reqs++;
   }

   if (n_reqs == 0) {
      *skip_reason = bson_strdup ("bulkWrite: empty requests array");
      return OP_SKIP;
   }
   if (n_reqs > 1) {
      /* Multi-request bulkWrite would need a batched wire command; we can't
       * emit that through individual Rust FFI calls, so skip the test. */
      *skip_reason =
         bson_strdup ("bulkWrite with multiple requests not supported");
      return OP_SKIP;
   }

   /* Single request — extract the model name and its inner args. */
   bson_iter_init (&ci, &reqs_arr);
   if (!bson_iter_next (&ci) || !BSON_ITER_HOLDS_DOCUMENT (&ci)) {
      return OP_FAIL;
   }
   uint32_t orl;
   const uint8_t *ord;
   bson_iter_document (&ci, &orl, &ord);
   bson_t op_doc;
   bson_init_static (&op_doc, ord, orl);

   /* op_doc has one key (the model name) whose value is the model args. */
   bson_iter_t oi;
   bson_iter_init (&oi, &op_doc);
   if (!bson_iter_next (&oi) || !BSON_ITER_HOLDS_DOCUMENT (&oi)) {
      return OP_FAIL;
   }
   const char *model = bson_iter_key (&oi);
   uint32_t al;
   const uint8_t *ad;
   bson_iter_document (&oi, &al, &ad);
   bson_t model_args;
   bson_init_static (&model_args, ad, al);

   /* Merge top-level bulkWrite options (let, comment) into the model args.
    * These are specified at the operation level (e.g. bulkWrite.let) but must
    * be forwarded to each individual sub-operation. */
   bson_t merged_args;
   bson_copy_to (&model_args, &merged_args);

   bson_iter_t bi;
   if (bson_iter_init_find (&bi, args, "let") && BSON_ITER_HOLDS_DOCUMENT (&bi)) {
      /* Only add "let" if the model doesn't already have one. */
      bson_iter_t check;
      if (!bson_iter_init_find (&check, &merged_args, "let")) {
         bson_append_iter (&merged_args, "let", -1, &bi);
      }
   }
   if (bson_iter_init_find (&bi, args, "comment")) {
      bson_iter_t check;
      if (!bson_iter_init_find (&check, &merged_args, "comment")) {
         bson_append_iter (&merged_args, "comment", -1, &bi);
      }
   }

   /* Dispatch to the matching single-op runner (no expectResult check). */
   op_status_t ret;
   if (strcmp (model, "insertOne") == 0) {
      ret = run_insert_one (coll, &merged_args, NULL, out_err);
   } else if (strcmp (model, "updateOne") == 0) {
      ret = run_update (coll, &merged_args, NULL, false, out_err);
   } else if (strcmp (model, "updateMany") == 0) {
      ret = run_update (coll, &merged_args, NULL, true, out_err);
   } else if (strcmp (model, "replaceOne") == 0) {
      ret = run_replace_one (coll, &merged_args, NULL, out_err);
   } else if (strcmp (model, "deleteOne") == 0) {
      ret = run_delete (coll, &merged_args, NULL, false, out_err);
   } else if (strcmp (model, "deleteMany") == 0) {
      ret = run_delete (coll, &merged_args, NULL, true, out_err);
   } else {
      bson_destroy (&merged_args);
      *skip_reason =
         bson_strdup_printf ("bulkWrite: unsupported model '%s'", model);
      return OP_SKIP;
   }
   bson_destroy (&merged_args);
   return ret;
}

