/* Commands generated by server monitoring, auth, or test infrastructure —
 * ignored for expectEvents. */
static const char *IGNORED_CMDS[] = {
   "hello", "isMaster", "ismaster", "endSessions",
   "saslStart", "saslContinue", "authenticate", "getnonce",
   "configureFailPoint",
   NULL
};

static bool
is_ignored_cmd (const char *name)
{
   for (int i = 0; IGNORED_CMDS[i]; i++) {
      if (strcasecmp (name, IGNORED_CMDS[i]) == 0) {
         return true;
      }
   }
   return false;
}

typedef enum { EVT_STARTED = 0, EVT_SUCCEEDED, EVT_FAILED } event_kind_t;

typedef struct {
   event_kind_t kind;
   char command_name[MAX_CMD_NAME_LEN];
   bson_t *command; /* heap-allocated; non-NULL only for started events */
   bson_t *reply;   /* heap-allocated; non-NULL only for succeeded events */
   char failure_message[256];
} collected_event_t;

typedef struct {
   collected_event_t events[MAX_EVENTS];
   int n;
} event_collector_t;

static void
collector_clear (event_collector_t *c)
{
   for (int i = 0; i < c->n; i++) {
      bson_destroy (c->events[i].command);
      bson_destroy (c->events[i].reply);
      c->events[i].command = NULL;
      c->events[i].reply = NULL;
   }
   c->n = 0;
}

static void
on_cmd_started (const mongoc_async_command_started_event_t *e, void *ud)
{
   event_collector_t *c = (event_collector_t *) ud;
   if (!e || c->n >= MAX_EVENTS) {
      return;
   }
   if (is_ignored_cmd (e->command_name)) {
      return;
   }
   collected_event_t *ev = &c->events[c->n];
   ev->kind = EVT_STARTED;
   strncpy (ev->command_name, e->command_name, MAX_CMD_NAME_LEN - 1);
   ev->command_name[MAX_CMD_NAME_LEN - 1] = '\0';
   if (e->command.data && e->command.len > 0) {
      bson_t tmp;
      bson_init_static (&tmp, (const uint8_t *) e->command.data, e->command.len);
      ev->command = bson_copy (&tmp);
   } else {
      ev->command = NULL;
   }
   ev->reply = NULL;
   ev->failure_message[0] = '\0';
   c->n++;
}

static void
on_cmd_succeeded (const mongoc_async_command_succeeded_event_t *e, void *ud)
{
   event_collector_t *c = (event_collector_t *) ud;
   if (!e || c->n >= MAX_EVENTS) {
      return;
   }
   if (is_ignored_cmd (e->command_name)) {
      return;
   }
   collected_event_t *ev = &c->events[c->n];
   ev->kind = EVT_SUCCEEDED;
   strncpy (ev->command_name, e->command_name, MAX_CMD_NAME_LEN - 1);
   ev->command_name[MAX_CMD_NAME_LEN - 1] = '\0';
   ev->command = NULL;
   if (e->reply.data && e->reply.len > 0) {
      bson_t tmp;
      bson_init_static (&tmp, (const uint8_t *) e->reply.data, e->reply.len);
      ev->reply = bson_copy (&tmp);
   } else {
      ev->reply = NULL;
   }
   ev->failure_message[0] = '\0';
   c->n++;
}

static void
on_cmd_failed (const mongoc_async_command_failed_event_t *e, void *ud)
{
   event_collector_t *c = (event_collector_t *) ud;
   if (!e || c->n >= MAX_EVENTS) {
      return;
   }
   if (is_ignored_cmd (e->command_name)) {
      return;
   }
   collected_event_t *ev = &c->events[c->n];
   ev->kind = EVT_FAILED;
   strncpy (ev->command_name, e->command_name, MAX_CMD_NAME_LEN - 1);
   ev->command_name[MAX_CMD_NAME_LEN - 1] = '\0';
   ev->command = NULL;
   ev->reply = NULL;
   strncpy (ev->failure_message, e->failure_message ? e->failure_message : "", 255);
   c->n++;
}

typedef enum {
   ENTITY_CLIENT = 0,
   ENTITY_DATABASE,
   ENTITY_COLLECTION,
} entity_type_t;

typedef struct {
   char id[128];
   entity_type_t type;
   union {
      mongoc_async_client_t *client;
      mongoc_async_database_t *db;
      mongoc_async_collection_t *coll;
   };
   /* Valid only when type == ENTITY_CLIENT; owns the collector. */
   event_collector_t *collector;
} entity_t;

typedef struct {
   entity_t entities[MAX_ENTITIES];
   int n;
} entity_map_t;

static entity_t *
entity_find (entity_map_t *m, const char *id)
{
   for (int i = 0; i < m->n; i++) {
      if (strcmp (m->entities[i].id, id) == 0) {
         return &m->entities[i];
      }
   }
   return NULL;
}

static void
entity_map_destroy (entity_map_t *m)
{
   /* Destroy in reverse creation order so children go before parents. */
   for (int i = m->n - 1; i >= 0; i--) {
      switch (m->entities[i].type) {
      case ENTITY_CLIENT:
         mongoc_async_client_destroy (m->entities[i].client);
         if (m->entities[i].collector) {
            collector_clear (m->entities[i].collector);
            bson_free (m->entities[i].collector);
            m->entities[i].collector = NULL;
         }
         break;
      case ENTITY_DATABASE:
         mongoc_async_database_destroy (m->entities[i].db);
         break;
      case ENTITY_COLLECTION:
         mongoc_async_collection_destroy (m->entities[i].coll);
         break;
      }
   }
   m->n = 0;
}

