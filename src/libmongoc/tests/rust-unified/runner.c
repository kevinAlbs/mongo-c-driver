/*
 * Configure a server failpoint via the admin database and record it for
 * cleanup.  args is the operation "arguments" document:
 *   { client: "<entity-id>", failPoint: { configureFailPoint: "...", mode: ..., data: {...} } }
 */
static op_status_t
run_fail_point (entity_map_t *map,
                const bson_t *args,
                failpoint_list_t *fps,
                char **skip_reason)
{
   bson_iter_t iter;

   /* Resolve the client entity. */
   if (!bson_iter_init_find (&iter, args, "client") ||
       !BSON_ITER_HOLDS_UTF8 (&iter)) {
      *skip_reason = bson_strdup ("failPoint: missing 'client'");
      return OP_SKIP;
   }
   const char *client_id = bson_iter_utf8 (&iter, NULL);
   entity_t *ce = entity_find (map, client_id);
   if (!ce || ce->type != ENTITY_CLIENT) {
      *skip_reason = bson_strdup ("failPoint: client entity not found");
      return OP_SKIP;
   }

   /* Extract the failPoint document. */
   if (!bson_iter_init_find (&iter, args, "failPoint") ||
       !BSON_ITER_HOLDS_DOCUMENT (&iter)) {
      *skip_reason = bson_strdup ("failPoint: missing 'failPoint' document");
      return OP_SKIP;
   }
   uint32_t fpl;
   const uint8_t *fpd;
   bson_iter_document (&iter, &fpl, &fpd);
   bson_t fp_doc;
   bson_init_static (&fp_doc, fpd, fpl);

   /* Extract the failpoint name for later cleanup. */
   bson_iter_t ni;
   if (!bson_iter_init_find (&ni, &fp_doc, "configureFailPoint") ||
       !BSON_ITER_HOLDS_UTF8 (&ni)) {
      *skip_reason = bson_strdup ("failPoint: missing 'configureFailPoint'");
      return OP_SKIP;
   }
   const char *fp_name = bson_iter_utf8 (&ni, NULL);

   /* Run configureFailPoint on the admin database. */
   mongoc_async_database_t *admin =
      mongoc_async_client_get_database (ce->client, "admin");
   mongoc_async_error_t *err = NULL;
   bson_owned_t *result =
      mongoc_async_database_run_command_await (admin, bson_to_rust_view (&fp_doc), &err);
   mongoc_async_database_destroy (admin);

   if (!result) {
      fprintf (stderr,
               "[rust-unified] failPoint: %s\n",
               err ? mongoc_async_error_get_message (err) : "unknown error");
      mongoc_async_error_destroy (err);
      return OP_FAIL;
   }
   bson_owned_destroy (result);

   /* Record for post-test cleanup. */
   if (fps->n < MAX_FAILPOINTS) {
      strncpy (fps->entries[fps->n].client_id, client_id, 127);
      fps->entries[fps->n].client_id[127] = '\0';
      strncpy (fps->entries[fps->n].fp_name, fp_name, 127);
      fps->entries[fps->n].fp_name[127] = '\0';
      fps->n++;
   }

   return OP_PASS;
}

/* -----------------------------------------------------------------------
 * Operation dispatcher
 * ----------------------------------------------------------------------- */

/*
 * Run one operation.  Returns OP_PASS, OP_FAIL, or OP_SKIP.
 * *skip_reason is allocated on OP_SKIP.
 */
static op_status_t
dispatch_operation (entity_map_t *map,
                    const bson_t *op,
                    failpoint_list_t *fps,
                    char **skip_reason)
{
   bson_iter_t iter;

   /* operation name */
   if (!bson_iter_init_find (&iter, op, "name") ||
       !BSON_ITER_HOLDS_UTF8 (&iter)) {
      return OP_FAIL;
   }
   const char *name = bson_iter_utf8 (&iter, NULL);

   /* object */
   if (!bson_iter_init_find (&iter, op, "object") ||
       !BSON_ITER_HOLDS_UTF8 (&iter)) {
      return OP_FAIL;
   }
   const char *object_id = bson_iter_utf8 (&iter, NULL);

   /* arguments — parse early so testRunner ops can use them too. */
   bson_t args;
   bson_t empty_args;
   bool static_args = false;
   if (bson_iter_init_find (&iter, op, "arguments") &&
       BSON_ITER_HOLDS_DOCUMENT (&iter)) {
      uint32_t al;
      const uint8_t *ad;
      bson_iter_document (&iter, &al, &ad);
      bson_init_static (&args, ad, al);
      static_args = true;
   } else {
      bson_init (&empty_args);
      args = empty_args;
   }

   /* testRunner operations — only failPoint is implemented. */
   if (strcmp (object_id, "testRunner") == 0) {
      if (strcmp (name, "failPoint") == 0) {
         if (!static_args) bson_destroy (&empty_args);
         return run_fail_point (map, &args, fps, skip_reason);
      }
      if (!static_args) bson_destroy (&empty_args);
      *skip_reason =
         bson_strdup_printf ("testRunner operation '%s' not supported", name);
      return OP_SKIP;
   }

   /* expectResult */
   const bson_t *expect_result_ptr = NULL;
   bson_t expect_result_doc;
   bson_t expect_result_arr;
   bool has_expect_result = false;

   if (bson_iter_init_find (&iter, op, "expectResult")) {
      has_expect_result = true;
      if (BSON_ITER_HOLDS_DOCUMENT (&iter)) {
         uint32_t el;
         const uint8_t *ed;
         bson_iter_document (&iter, &el, &ed);
         bson_init_static (&expect_result_doc, ed, el);
         expect_result_ptr = &expect_result_doc;
      } else if (BSON_ITER_HOLDS_ARRAY (&iter)) {
         uint32_t el;
         const uint8_t *ed;
         bson_iter_array (&iter, &el, &ed);
         bson_init_static (&expect_result_arr, ed, el);
         expect_result_ptr = &expect_result_arr;
      }
   }

   /* expectError — parse supported fields; skip on unsupported ones. */
   bool has_expect_error = false;
   bool ee_is_error = true;            /* operation should fail; isError defaults to true per spec */
   bool ee_is_client_error_set = false;
   bool ee_is_client_error = false;
   bool ee_error_code_set = false;
   int32_t ee_error_code = 0;
   const char *ee_error_contains = NULL; /* substring to find in message */
   bool ee_has_expect_result = false;   /* expectResult inside expectError */
   bool ee_expect_result_is_null = false;
   bson_t ee_expect_result;             /* valid when ee_has_expect_result && !ee_expect_result_is_null */
   bool ee_has_writeErrors = false;     /* writeErrors inside expectError */
   bson_t ee_writeErrors;               /* valid when ee_has_writeErrors */

   if (bson_iter_init_find (&iter, op, "expectError") &&
       BSON_ITER_HOLDS_DOCUMENT (&iter)) {
      has_expect_error = true;
      uint32_t eel;
      const uint8_t *eed;
      bson_iter_document (&iter, &eel, &eed);
      bson_t ee;
      bson_init_static (&ee, eed, eel);

      bson_iter_t eei;
      bson_iter_init (&eei, &ee);
      while (bson_iter_next (&eei)) {
         const char *k = bson_iter_key (&eei);
         if (strcmp (k, "isError") == 0) {
            ee_is_error = bson_iter_bool (&eei);
         } else if (strcmp (k, "isClientError") == 0) {
            ee_is_client_error_set = true;
            ee_is_client_error = bson_iter_bool (&eei);
         } else if (strcmp (k, "errorCode") == 0) {
            ee_error_code_set = true;
            ee_error_code = (int32_t) bson_iter_as_int64 (&eei);
         } else if (strcmp (k, "errorContains") == 0) {
            ee_error_contains = bson_iter_utf8 (&eei, NULL);
         } else if (strcmp (k, "errorResponse") == 0) {
            /* errorResponse contents are not validated — we only check
             * errorCode and errorContains, so we simply skip the field. */
         } else if (strcmp (k, "expectResult") == 0) {
            /* Partial result expected on failure (e.g. clientBulkWrite). */
            ee_has_expect_result = true;
            if (BSON_ITER_HOLDS_DOCUMENT (&eei)) {
               uint32_t rl;
               const uint8_t *rd;
               bson_iter_document (&eei, &rl, &rd);
               bson_init_static (&ee_expect_result, rd, rl);
            } else {
               ee_expect_result_is_null = true;
            }
         } else if (strcmp (k, "writeErrors") == 0 &&
                    BSON_ITER_HOLDS_DOCUMENT (&eei)) {
            ee_has_writeErrors = true;
            uint32_t wl;
            const uint8_t *wd;
            bson_iter_document (&eei, &wl, &wd);
            bson_init_static (&ee_writeErrors, wd, wl);
         } else {
            /* Unsupported: writeConcernErrors, isTimeoutError, errorCodeName,
             * errorLabelsContain, errorLabelsOmit — skip this test. */
            *skip_reason = bson_strdup_printf (
               "Operation '%s' has unsupported expectError field '%s'",
               name,
               k);
            if (!static_args) bson_destroy (&empty_args);
            return OP_SKIP;
         }
      }
   }

   /* Find the entity. */
   entity_t *entity = entity_find (map, object_id);
   if (!entity) {
      fprintf (stderr,
               "[rust-unified] entity '%s' not found\n",
               object_id);
      if (!static_args) bson_destroy (&empty_args);
      return OP_FAIL;
   }

   mongoc_async_error_t *captured_err = NULL;
   bson_owned_t *captured_partial_result = NULL; /* set by clientBulkWrite on partial failure */
   op_status_t status;

   if (entity->type == ENTITY_COLLECTION) {
      mongoc_async_collection_t *coll = entity->coll;

      if (strcmp (name, "insertOne") == 0) {
         status = run_insert_one (coll, &args, expect_result_ptr, &captured_err);
      } else if (strcmp (name, "insertMany") == 0) {
         status = run_insert_many (coll, &args, expect_result_ptr, &captured_err);
      } else if (strcmp (name, "find") == 0) {
         status = run_find (coll, &args, expect_result_ptr, &captured_err);
      } else if (strcmp (name, "updateOne") == 0) {
         status = run_update (
            coll, &args, expect_result_ptr, false, &captured_err);
      } else if (strcmp (name, "updateMany") == 0) {
         status = run_update (
            coll, &args, expect_result_ptr, true, &captured_err);
      } else if (strcmp (name, "replaceOne") == 0) {
         status = run_replace_one (
            coll, &args, expect_result_ptr, &captured_err);
      } else if (strcmp (name, "deleteOne") == 0) {
         status =
            run_delete (coll, &args, expect_result_ptr, false, &captured_err);
      } else if (strcmp (name, "deleteMany") == 0) {
         status =
            run_delete (coll, &args, expect_result_ptr, true, &captured_err);
      } else if (strcmp (name, "findOne") == 0) {
         status = run_find_one (coll, &args, expect_result_ptr, &captured_err);
      } else if (strcmp (name, "aggregate") == 0) {
         status = run_aggregate_coll (coll, &args, expect_result_ptr, &captured_err);
      } else if (strcmp (name, "countDocuments") == 0) {
         status = run_count_documents (coll, &args, expect_result_ptr, &captured_err);
      } else if (strcmp (name, "estimatedDocumentCount") == 0) {
         status = run_estimated_document_count (coll, &args, expect_result_ptr, &captured_err);
      } else if (strcmp (name, "distinct") == 0) {
         status = run_distinct (coll, &args, expect_result_ptr, &captured_err);
      } else if (strcmp (name, "findOneAndDelete") == 0) {
         status = run_find_one_and_delete (coll, &args, expect_result_ptr, &captured_err);
      } else if (strcmp (name, "findOneAndUpdate") == 0) {
         status = run_find_one_and_update (coll, &args, expect_result_ptr, &captured_err);
      } else if (strcmp (name, "findOneAndReplace") == 0) {
         status = run_find_one_and_replace (coll, &args, expect_result_ptr, &captured_err);
      } else if (strcmp (name, "createIndex") == 0) {
         bson_iter_t kiter;
         if (!bson_iter_init_find (&kiter, &args, "keys") ||
             !BSON_ITER_HOLDS_DOCUMENT (&kiter)) {
            status = OP_FAIL;
         } else {
            uint32_t kl;
            const uint8_t *kd;
            bson_iter_document (&kiter, &kl, &kd);
            bson_t kbson;
            bson_init_static (&kbson, kd, kl);
            bool unique = false;
            bson_iter_t ui;
            if (bson_iter_init_find (&ui, &args, "unique") &&
                BSON_ITER_HOLDS_BOOL (&ui)) {
               unique = bson_iter_bool (&ui);
            }
            mongoc_async_error_t *ierr = NULL;
            bool ok = mongoc_async_collection_create_index_await (
               coll, bson_to_rust_view (&kbson), unique, &ierr);
            if (ok) {
               status = OP_PASS;
            } else {
               if (captured_err) mongoc_async_error_destroy (captured_err);
               captured_err = ierr;
               status = OP_FAIL;
            }
         }
      } else if (strcmp (name, "bulkWrite") == 0) {
         status = run_bulk_write (coll, &args, &captured_err, skip_reason);
      } else {
         *skip_reason =
            bson_strdup_printf ("Unsupported collection op: %s", name);
         status = OP_SKIP;
      }

   } else if (entity->type == ENTITY_DATABASE) {
      mongoc_async_database_t *db = entity->db;

      if (strcmp (name, "runCommand") == 0) {
         status = run_run_command (db, &args, expect_result_ptr, &captured_err);
      } else if (strcmp (name, "aggregate") == 0) {
         status = run_aggregate_db (db, &args, expect_result_ptr, &captured_err);
      } else if (strcmp (name, "dropCollection") == 0) {
         bson_iter_t di2;
         const char *coll_name = NULL;
         if (bson_iter_init_find (&di2, &args, "collection") &&
             BSON_ITER_HOLDS_UTF8 (&di2)) {
            coll_name = bson_iter_utf8 (&di2, NULL);
         }
         if (coll_name) {
            mongoc_async_database_drop_collection_await (db, coll_name);
         }
         status = OP_PASS;
      } else if (strcmp (name, "createCollection") == 0) {
         bson_iter_t di2;
         const char *coll_name = NULL;
         if (bson_iter_init_find (&di2, &args, "collection") &&
             BSON_ITER_HOLDS_UTF8 (&di2)) {
            coll_name = bson_iter_utf8 (&di2, NULL);
         }
         if (!coll_name) {
            status = OP_FAIL;
         } else {
            /* Build a `create` command, forwarding viewOn and pipeline. */
            bson_t cmd;
            bson_init (&cmd);
            BSON_APPEND_UTF8 (&cmd, "create", coll_name);
            bson_iter_t voi;
            if (bson_iter_init_find (&voi, &args, "viewOn") &&
                BSON_ITER_HOLDS_UTF8 (&voi)) {
               BSON_APPEND_UTF8 (&cmd, "viewOn", bson_iter_utf8 (&voi, NULL));
            }
            bson_iter_t pli;
            if (bson_iter_init_find (&pli, &args, "pipeline") &&
                BSON_ITER_HOLDS_ARRAY (&pli)) {
               uint32_t pl;
               const uint8_t *pd;
               bson_iter_array (&pli, &pl, &pd);
               bson_t parr;
               bson_init_static (&parr, pd, pl);
               BSON_APPEND_ARRAY (&cmd, "pipeline", &parr);
            }
            mongoc_async_error_t *cerr = NULL;
            bson_owned_t *reply =
               mongoc_async_database_run_command_await (db, bson_to_rust_view (&cmd), &cerr);
            bson_destroy (&cmd);
            if (reply) {
               bson_owned_destroy (reply);
               status = OP_PASS;
            } else {
               if (captured_err) mongoc_async_error_destroy (captured_err);
               captured_err = cerr;
               status = OP_FAIL;
            }
         }
      } else if (strcmp (name, "modifyCollection") == 0) {
         /* Translate to collMod command: {collMod: <coll>, ...args} */
         bson_iter_t cni;
         if (!bson_iter_init_find (&cni, &args, "collection") ||
             !BSON_ITER_HOLDS_UTF8 (&cni)) {
            status = OP_FAIL;
         } else {
            const char *coll_name2 = bson_iter_utf8 (&cni, NULL);
            bson_t cmd;
            bson_init (&cmd);
            BSON_APPEND_UTF8 (&cmd, "collMod", coll_name2);
            /* Append any remaining arguments (validator, validationLevel, etc.) */
            bson_iter_t ai;
            bson_iter_init (&ai, &args);
            while (bson_iter_next (&ai)) {
               const char *ak = bson_iter_key (&ai);
               if (strcmp (ak, "collection") == 0) continue;
               bson_append_iter (&cmd, ak, -1, &ai);
            }
            mongoc_async_error_t *cerr = NULL;
            bson_owned_t *reply =
               mongoc_async_database_run_command_await (db, bson_to_rust_view (&cmd), &cerr);
            bson_destroy (&cmd);
            if (reply) {
               bson_owned_destroy (reply);
               status = OP_PASS;
            } else {
               if (captured_err) mongoc_async_error_destroy (captured_err);
               captured_err = cerr;
               status = OP_FAIL;
            }
         }
      } else if (strcmp (name, "listCollections") == 0) {
         *skip_reason =
            bson_strdup_printf ("Unsupported database op: %s", name);
         status = OP_SKIP;
      } else {
         *skip_reason =
            bson_strdup_printf ("Unknown database op: %s", name);
         status = OP_SKIP;
      }

   } else if (entity->type == ENTITY_CLIENT) {
      mongoc_async_client_t *cli = entity->client;

      if (strcmp (name, "clientBulkWrite") == 0) {
         /* Build the args BSON to pass to Rust: { "models": [...], ... }
          * The spec stores models under "models", not "requests". We pass
          * the entire args document through. */
         mongoc_async_error_t *bw_err = NULL;
         bson_owned_t *bw_result =
            mongoc_async_client_bulk_write_await (cli, bson_to_rust_view (&args), &bw_err, &captured_partial_result);
         if (bw_result) {
            if (expect_result_ptr) {
               bson_unowned_t rv = bson_owned_as_view (bw_result);
               bson_t actual;
               bson_init_static (&actual, (const uint8_t *) rv.data, rv.len);
               bool ok2 = compare_result (&actual, expect_result_ptr, "clientBulkWrite");
               bson_owned_destroy (bw_result);
               status = ok2 ? OP_PASS : OP_FAIL;
            } else {
               bson_owned_destroy (bw_result);
               status = OP_PASS;
            }
         } else {
            if (captured_err) mongoc_async_error_destroy (captured_err);
            captured_err = bw_err;
            status = OP_FAIL;
         }
      } else {
         *skip_reason =
            bson_strdup_printf ("Unsupported client op: %s", name);
         status = OP_SKIP;
      }

   } else {
      *skip_reason =
         bson_strdup_printf ("Op '%s' on unsupported entity type", name);
      status = OP_SKIP;
   }

   /* Handle expectError validation after the operation completes.
    * If expectError is present, isError defaults to true per the spec. */
   if (status != OP_SKIP && has_expect_error && ee_is_error) {
      if (status == OP_PASS) {
         fprintf (stderr,
                  "[rust-unified] %s: expected error but operation succeeded\n",
                  name);
         status = OP_FAIL;
      } else {
         /* Operation failed as expected — validate error properties. */
         bool err_ok = true;

         if (ee_is_client_error_set && captured_err) {
            bool is_server = mongoc_async_error_is_server_error (captured_err);
            bool got_client_err = !is_server;
            if (got_client_err != ee_is_client_error) {
               fprintf (stderr,
                        "[rust-unified] %s: isClientError expected=%s got=%s\n",
                        name,
                        ee_is_client_error ? "true" : "false",
                        got_client_err ? "true" : "false");
               err_ok = false;
            }
         }

         if (ee_error_code_set && captured_err) {
            int32_t got_code = mongoc_async_error_get_server_code (captured_err);
            if (got_code != ee_error_code) {
               fprintf (stderr,
                        "[rust-unified] %s: errorCode expected=%d got=%d\n",
                        name,
                        (int) ee_error_code,
                        (int) got_code);
               err_ok = false;
            }
         }

         if (ee_error_contains && captured_err) {
            const char *msg = mongoc_async_error_get_message (captured_err);
            if (!msg || !strstr (msg, ee_error_contains)) {
               fprintf (stderr,
                        "[rust-unified] %s: errorContains '%s' not found in "
                        "'%s'\n",
                        name,
                        ee_error_contains,
                        msg ? msg : "(null)");
               err_ok = false;
            }
         }

         /* expectResult inside expectError: compare partial result.
          * If expectResult starts with $$unsetOrMatches, the partial result
          * may be absent; compare_result handles this by returning true
          * immediately when it sees $$unsetOrMatches at top level.
          * Otherwise a non-null partial result is required. */
         if (ee_has_expect_result) {
            if (ee_expect_result_is_null) {
               /* Explicit null: expect no partial result. */
               if (captured_partial_result) {
                  fprintf (stderr,
                           "[rust-unified] %s: expectResult is null but partial result returned\n",
                           name);
                  err_ok = false;
               }
            } else if (captured_partial_result) {
               /* Partial result present: compare it against expectResult. */
               bson_unowned_t pv = bson_owned_as_view (captured_partial_result);
               bson_t actual_partial;
               bson_init_static (&actual_partial, (const uint8_t *) pv.data, pv.len);
               if (!compare_result (&actual_partial, &ee_expect_result, "expectResult")) {
                  err_ok = false;
               }
            } else {
               /* No partial result: use an empty doc as actual.
                * compare_result returns true for $$unsetOrMatches (pass),
                * false for any concrete field expectations (fail). */
               bson_t empty_actual;
               bson_init (&empty_actual);
               if (!compare_result (&empty_actual, &ee_expect_result, "expectResult")) {
                  fprintf (stderr,
                           "[rust-unified] %s: expectResult set but no partial result returned\n",
                           name);
                  err_ok = false;
               }
               bson_destroy (&empty_actual);
            }
         }

         /* writeErrors inside expectError: compare per-op write errors embedded
          * in the partial result document (under the "writeErrors" key). */
         if (ee_has_writeErrors) {
            bson_t actual_we;
            bool actual_we_found = false;
            if (captured_partial_result) {
               bson_unowned_t pv = bson_owned_as_view (captured_partial_result);
               bson_t actual_partial;
               bson_init_static (
                  &actual_partial, (const uint8_t *) pv.data, pv.len);
               bson_iter_t wi;
               if (bson_iter_init_find (&wi, &actual_partial, "writeErrors") &&
                   BSON_ITER_HOLDS_DOCUMENT (&wi)) {
                  uint32_t wl;
                  const uint8_t *wd;
                  bson_iter_document (&wi, &wl, &wd);
                  bson_init_static (&actual_we, wd, wl);
                  actual_we_found = true;
               }
            }
            if (!actual_we_found) {
               bson_init (&actual_we);
            }
            if (!compare_write_errors (&actual_we, &ee_writeErrors, name)) {
               err_ok = false;
            }
            if (!actual_we_found) {
               bson_destroy (&actual_we);
            }
         }

         mongoc_async_error_destroy (captured_err);
         captured_err = NULL;
         status = err_ok ? OP_PASS : OP_FAIL;
      }
   }

   /* If the Rust driver rejected an unacknowledged write concern, skip the
    * test rather than failing — we simply don't support w:0 operations. */
   if (status == OP_FAIL && captured_err) {
      const char *msg = mongoc_async_error_get_message (captured_err);
      if (msg &&
          strstr (msg, "Unacknowledged write concerns are not supported")) {
         mongoc_async_error_destroy (captured_err);
         captured_err = NULL;
         *skip_reason =
            bson_strdup ("Unacknowledged writes not supported by Rust driver");
         if (!static_args) bson_destroy (&empty_args);
         return OP_SKIP;
      }
   }

   if (captured_err) {
      mongoc_async_error_destroy (captured_err);
   }
   if (captured_partial_result) {
      bson_owned_destroy (captured_partial_result);
   }
   if (!static_args) bson_destroy (&empty_args);
   return status;
}

