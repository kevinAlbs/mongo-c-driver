static bson_unowned_t
bson_to_rust_view (const bson_t *b)
{
   bson_unowned_t v;
   v.data = bson_get_data (b);
   v.len = b->len;
   return v;
}

/* Get a sub-document field as a static bson_t (no allocation, no destroy). */
static bool
get_doc_field (const bson_t *doc, const char *key, bson_t *out)
{
   bson_iter_t iter;
   if (!bson_iter_init_find (&iter, doc, key)) {
      return false;
   }
   if (!BSON_ITER_HOLDS_DOCUMENT (&iter)) {
      return false;
   }
   uint32_t len;
   const uint8_t *data;
   bson_iter_document (&iter, &len, &data);
   bson_init_static (out, data, len);
   return true;
}

/* -----------------------------------------------------------------------
 * Server version / requirements checking
 * ----------------------------------------------------------------------- */

/*
 * Approximate map from server major.minor → minimum wire protocol version.
 * Used with test_framework_max_wire_version_at_least().
 */
static int
server_ver_to_wire (int major, int minor)
{
   if (major >= 8) {
      return 25;
   }
   if (major == 7) {
      /* 7.0=21, 7.1=22, 7.2=23, 7.3=24; cap minor at 3 so "7.99" maps to 24
       * and maxServerVersion "7.99" correctly excludes 8.0+ servers. */
      if (minor > 3) minor = 3;
      return 21 + (minor > 0 ? minor - 1 : 0);
   }
   if (major == 6) {
      /* 6.0=17, 6.1=18, ... cap minor at 3 */
      if (minor > 3) minor = 3;
      return 17 + (minor > 0 ? minor - 1 : 0);
   }
   if (major == 5) {
      if (minor == 0) return 13;
      if (minor == 1) return 14;
      return 15 + (minor - 2);
   }
   if (major == 4) {
      if (minor >= 4) return 9;
      if (minor >= 2) return 8;
      return 7;
   }
   return 0;
}

static bool
parse_semver (const char *s, int *major, int *minor, int *patch)
{
   *major = *minor = *patch = 0;
   return s && (sscanf (s, "%d.%d.%d", major, minor, patch) >= 2);
}

/*
 * Check one runOnRequirements entry.
 * Returns true if the requirement is satisfied.
 * On failure, allocates *skip_reason (caller frees with bson_free).
 */
static bool
check_one_req (const bson_t *req, char **skip_reason)
{
   bson_iter_t iter;
   bson_iter_init (&iter, req);

   while (bson_iter_next (&iter)) {
      const char *key = bson_iter_key (&iter);

      if (strcmp (key, "minServerVersion") == 0) {
         const char *ver = bson_iter_utf8 (&iter, NULL);
         int maj, min, pat;
         if (parse_semver (ver, &maj, &min, &pat)) {
            int needed = server_ver_to_wire (maj, min);
            /* needed==0 means pre-4.0; all test servers are newer, so skip
             * the wire-version check to avoid the version>0 assertion. */
            if (needed > 0 &&
                !test_framework_max_wire_version_at_least (needed)) {
               *skip_reason =
                  bson_strdup_printf ("minServerVersion %s not met", ver);
               return false;
            }
         }
         continue;
      }

      if (strcmp (key, "maxServerVersion") == 0) {
         const char *ver = bson_iter_utf8 (&iter, NULL);
         int maj, min, pat;
         if (parse_semver (ver, &maj, &min, &pat)) {
            int max_wv = server_ver_to_wire (maj, min);
            /* max_wv==0 means pre-4.0; our server is definitely newer. */
            if (max_wv == 0) {
               *skip_reason =
                  bson_strdup_printf ("maxServerVersion %s exceeded", ver);
               return false;
            }
            if (test_framework_max_wire_version_at_least (max_wv + 1)) {
               *skip_reason =
                  bson_strdup_printf ("maxServerVersion %s exceeded", ver);
               return false;
            }
         }
         continue;
      }

      if (strcmp (key, "topologies") == 0) {
         bson_t topos;
         bson_iter_bson (&iter, &topos);
         bool found = false;
         bson_iter_t ti;
         bson_iter_init (&ti, &topos);
         while (bson_iter_next (&ti)) {
            const char *t = bson_iter_utf8 (&ti, NULL);
            if (strcmp (t, "single") == 0 && !test_framework_is_replset () &&
                !test_framework_is_mongos ()) {
               found = true;
               break;
            }
            if (strcmp (t, "replicaset") == 0 &&
                test_framework_is_replset ()) {
               found = true;
               break;
            }
            if ((strcmp (t, "sharded") == 0 ||
                 strcmp (t, "sharded-replicaset") == 0) &&
                test_framework_is_mongos ()) {
               found = true;
               break;
            }
         }
         if (!found) {
            *skip_reason = bson_strdup ("Topology requirement not met");
            return false;
         }
         continue;
      }

      /* auth, serverParameters, serverless, csfle — ignore for now. */
   }
   return true;
}

/*
 * Returns true if at least one entry in requirements_array is satisfied
 * (or if requirements_array is NULL/empty).
 */
static bool
check_run_on_requirements (const bson_t *arr, char **skip_reason)
{
   if (!arr) {
      return true;
   }

   bson_iter_t iter;
   bson_iter_init (&iter, arr);
   char *last_reason = NULL;

   while (bson_iter_next (&iter)) {
      bson_t req;
      bson_iter_bson (&iter, &req);
      char *reason = NULL;
      if (check_one_req (&req, &reason)) {
         bson_free (last_reason);
         return true;
      }
      bson_free (last_reason);
      last_reason = reason;
   }

   *skip_reason =
      last_reason ? last_reason : bson_strdup ("runOnRequirements not met");
   return false;
}

/* -----------------------------------------------------------------------
 * Initial data loading
 * ----------------------------------------------------------------------- */

static void
load_initial_data (const bson_t *initial_data)
{
   if (!initial_data) {
      return;
   }

   mongoc_client_t *client = test_framework_new_default_client ();

   bson_iter_t iter;
   bson_iter_init (&iter, initial_data);
   while (bson_iter_next (&iter)) {
      bson_t entry;
      bson_iter_bson (&iter, &entry);

      const char *coll_name = NULL, *db_name = NULL;
      bson_iter_t ei;
      bson_iter_init (&ei, &entry);
      while (bson_iter_next (&ei)) {
         const char *k = bson_iter_key (&ei);
         if (strcmp (k, "collectionName") == 0) {
            coll_name = bson_iter_utf8 (&ei, NULL);
         } else if (strcmp (k, "databaseName") == 0) {
            db_name = bson_iter_utf8 (&ei, NULL);
         }
      }
      if (!coll_name || !db_name) {
         continue;
      }

      mongoc_collection_t *coll =
         mongoc_client_get_collection (client, db_name, coll_name);
      mongoc_collection_drop (coll, NULL);

      /* "documents" is a BSON array of initial docs to insert. */
      bson_iter_init_find (&ei, &entry, "documents");
      if (BSON_ITER_HOLDS_ARRAY (&ei)) {
         uint32_t alen;
         const uint8_t *adata;
         bson_iter_array (&ei, &alen, &adata);
         bson_t arr;
         bson_init_static (&arr, adata, alen);
         bson_iter_t di;
         bson_iter_init (&di, &arr);
         while (bson_iter_next (&di)) {
            if (!BSON_ITER_HOLDS_DOCUMENT (&di)) {
               continue;
            }
            uint32_t dlen;
            const uint8_t *ddata;
            bson_iter_document (&di, &dlen, &ddata);
            bson_t doc;
            bson_init_static (&doc, ddata, dlen);
            bson_error_t err;
            if (!mongoc_collection_insert_one (coll, &doc, NULL, NULL, &err)) {
               fprintf (stderr,
                        "[rust-unified] initial data insert failed: %s\n",
                        err.message);
            }
         }
      }

      mongoc_collection_destroy (coll);
   }

   mongoc_client_destroy (client);
}

