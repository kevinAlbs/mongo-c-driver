/*
 * Returns true if the expected value at `ei` is a document-form special
 * operator that allows the key to be absent (e.g. $$unsetOrMatches or any
 * other $$ operator at the document level).
 */
static bool
is_unset_ok_operator (const bson_iter_t *ei)
{
   if (bson_iter_type (ei) != BSON_TYPE_DOCUMENT) {
      return false;
   }
   uint32_t dl;
   const uint8_t *dd;
   bson_iter_document (ei, &dl, &dd);
   bson_t sub;
   bson_init_static (&sub, dd, dl);
   bson_iter_t si;
   bson_iter_init (&si, &sub);
   if (bson_iter_next (&si)) {
      const char *k = bson_iter_key (&si);
      /* Any $$ operator in document form is treated as "unset is ok". */
      if (k[0] == '$' && k[1] == '$') {
         return true;
      }
   }
   return false;
}

/*
 * Partial BSON match: every field in `expected` must appear in `actual` with
 * an equal value.  Extra fields in `actual` are ignored.  Values that are
 * strings starting with "$$" are special operators and are skipped (always
 * pass).  Document values `{ "$$unsetOrMatches": <v> }` allow the key to be
 * absent OR equal to <v>.  Recursively applied to sub-documents and arrays.
 */
static bool
bson_partial_match (const bson_t *actual, const bson_t *expected)
{
   bson_iter_t ei;
   bson_iter_init (&ei, expected);

   while (bson_iter_next (&ei)) {
      const char *key = bson_iter_key (&ei);
      bson_type_t exp_type = bson_iter_type (&ei);

      /* Skip special operators at the key level (e.g. $$type, $$exists). */
      if (key[0] == '$' && key[1] == '$') {
         continue;
      }

      bson_iter_t ai;
      if (!bson_iter_init_find (&ai, actual, key)) {
         /* Field absent in actual: pass if the expected value is a $$
          * operator document (e.g. $$unsetOrMatches). */
         if (is_unset_ok_operator (&ei)) {
            continue;
         }
         fprintf (stderr, "[rust-unified] expectEvents: field '%s' missing\n", key);
         return false;
      }
      bson_type_t act_type = bson_iter_type (&ai);

      /* If expected value is a document-form $$ operator, skip value check. */
      if (exp_type == BSON_TYPE_DOCUMENT && is_unset_ok_operator (&ei)) {
         /* For $$unsetOrMatches the field is present; any value is accepted
          * by a simple implementation (full value-match is complex). */
         continue;
      }

      if (exp_type == BSON_TYPE_UTF8) {
         const char *exp_val = bson_iter_utf8 (&ei, NULL);
         /* Skip if the value itself is a special operator. */
         if (exp_val && exp_val[0] == '$' && exp_val[1] == '$') {
            continue;
         }
         if (act_type != BSON_TYPE_UTF8) {
            fprintf (stderr,
                     "[rust-unified] expectEvents: field '%s' type mismatch\n",
                     key);
            return false;
         }
         const char *act_val = bson_iter_utf8 (&ai, NULL);
         if (strcmp (exp_val, act_val) != 0) {
            fprintf (stderr,
                     "[rust-unified] expectEvents: field '%s': expected '%s', got '%s'\n",
                     key,
                     exp_val,
                     act_val);
            return false;
         }
      } else if (exp_type == BSON_TYPE_INT32 || exp_type == BSON_TYPE_INT64) {
         int64_t ev = (exp_type == BSON_TYPE_INT32) ? (int64_t) bson_iter_int32 (&ei)
                                                     : bson_iter_int64 (&ei);
         if (act_type != BSON_TYPE_INT32 && act_type != BSON_TYPE_INT64) {
            fprintf (stderr,
                     "[rust-unified] expectEvents: field '%s' not numeric\n",
                     key);
            return false;
         }
         int64_t av =
            (act_type == BSON_TYPE_INT32) ? (int64_t) bson_iter_int32 (&ai) : bson_iter_int64 (&ai);
         if (ev != av) {
            fprintf (stderr,
                     "[rust-unified] expectEvents: field '%s': expected %" PRId64 ", got %" PRId64 "\n",
                     key,
                     ev,
                     av);
            return false;
         }
      } else if (exp_type == BSON_TYPE_BOOL) {
         if (act_type != BSON_TYPE_BOOL) {
            fprintf (stderr,
                     "[rust-unified] expectEvents: field '%s' not bool\n",
                     key);
            return false;
         }
         if (bson_iter_bool (&ei) != bson_iter_bool (&ai)) {
            fprintf (stderr,
                     "[rust-unified] expectEvents: field '%s' bool mismatch\n",
                     key);
            return false;
         }
      } else if (exp_type == BSON_TYPE_DOCUMENT) {
         if (act_type != BSON_TYPE_DOCUMENT) {
            fprintf (stderr,
                     "[rust-unified] expectEvents: field '%s' not document\n",
                     key);
            return false;
         }
         uint32_t el, al;
         const uint8_t *ed, *ad;
         bson_iter_document (&ei, &el, &ed);
         bson_iter_document (&ai, &al, &ad);
         bson_t exp_sub, act_sub;
         bson_init_static (&exp_sub, ed, el);
         bson_init_static (&act_sub, ad, al);
         if (!bson_partial_match (&act_sub, &exp_sub)) {
            return false;
         }
      } else if (exp_type == BSON_TYPE_ARRAY) {
         if (act_type != BSON_TYPE_ARRAY) {
            fprintf (stderr,
                     "[rust-unified] expectEvents: field '%s' not array\n",
                     key);
            return false;
         }
         /* Treat arrays as documents keyed by index for recursive matching. */
         uint32_t el, al;
         const uint8_t *ed, *ad;
         bson_iter_array (&ei, &el, &ed);
         bson_iter_array (&ai, &al, &ad);
         bson_t exp_arr, act_arr;
         bson_init_static (&exp_arr, ed, el);
         bson_init_static (&act_arr, ad, al);
         if (!bson_partial_match (&act_arr, &exp_arr)) {
            return false;
         }
      }
      /* Other types (OID, double, null, binary…) — skip */
   }
   return true;
}

/*
 * Verify that collected events on each client match the `expectEvents` array
 * from the test JSON.  Returns false on mismatch.
 *
 * Expected format:
 *   [ { "client": "<id>", "events": [ { "commandStartedEvent": { ... } }, ... ] }, ... ]
 *
 * Only commandStartedEvent is fully validated.  commandSucceededEvent and
 * commandFailedEvent presence is checked but the payload is not inspected.
 */
static bool
check_expect_events (const bson_t *expect_arr, entity_map_t *map)
{
   bson_iter_t iter;
   bson_iter_init (&iter, expect_arr);

   while (bson_iter_next (&iter)) {
      bson_t entry;
      bson_iter_bson (&iter, &entry);

      /* "client" field — which client's events to check. */
      bson_iter_t ci;
      if (!bson_iter_init_find (&ci, &entry, "client")) {
         continue;
      }
      const char *client_id = bson_iter_utf8 (&ci, NULL);
      entity_t *ce = entity_find (map, client_id);
      if (!ce || ce->type != ENTITY_CLIENT || !ce->collector) {
         fprintf (stderr,
                  "[rust-unified] expectEvents: client '%s' not found\n",
                  client_id);
         return false;
      }
      event_collector_t *coll = ce->collector;

      /* "events" array — expected events in order. */
      bson_iter_t evi;
      if (!bson_iter_init_find (&evi, &entry, "events") || !BSON_ITER_HOLDS_ARRAY (&evi)) {
         continue;
      }
      uint32_t el;
      const uint8_t *ed;
      bson_iter_array (&evi, &el, &ed);
      bson_t exp_events;
      bson_init_static (&exp_events, ed, el);

      bson_iter_t ei;
      bson_iter_init (&ei, &exp_events);
      int collected_idx = 0;

      while (bson_iter_next (&ei)) {
         bson_t exp_event;
         bson_iter_bson (&ei, &exp_event);

         /* Each expected event is { "commandStartedEvent": {...} } etc. */
         bson_iter_t eti;
         bson_iter_init (&eti, &exp_event);
         if (!bson_iter_next (&eti)) {
            continue;
         }
         const char *event_type = bson_iter_key (&eti);
         bson_t event_spec;
         bson_iter_bson (&eti, &event_spec);

         /* Determine expected kind. */
         event_kind_t exp_kind;
         if (strcmp (event_type, "commandStartedEvent") == 0) {
            exp_kind = EVT_STARTED;
         } else if (strcmp (event_type, "commandSucceededEvent") == 0) {
            exp_kind = EVT_SUCCEEDED;
         } else if (strcmp (event_type, "commandFailedEvent") == 0) {
            exp_kind = EVT_FAILED;
         } else {
            /* Unknown event type — skip. */
            continue;
         }

         /* Advance to next collected event of matching kind. */
         while (collected_idx < coll->n &&
                coll->events[collected_idx].kind != exp_kind) {
            collected_idx++;
         }

         if (collected_idx >= coll->n) {
            fprintf (stderr,
                     "[rust-unified] expectEvents: no more %s events for client '%s'\n",
                     event_type,
                     client_id);
            return false;
         }

         collected_event_t *ev = &coll->events[collected_idx++];

         /* Check commandName if the spec has one. */
         bson_iter_t si;
         if (bson_iter_init_find (&si, &event_spec, "commandName")) {
            const char *exp_name = bson_iter_utf8 (&si, NULL);
            if (strcmp (exp_name, ev->command_name) != 0) {
               fprintf (stderr,
                        "[rust-unified] expectEvents: commandName mismatch: "
                        "expected '%s', got '%s'\n",
                        exp_name,
                        ev->command_name);
               return false;
            }
         }

         /* For started events: partial-match the command document if given. */
         if (exp_kind == EVT_STARTED && ev->command) {
            bson_t exp_cmd;
            if (get_doc_field (&event_spec, "command", &exp_cmd)) {
               if (!bson_partial_match (ev->command, &exp_cmd)) {
                  fprintf (stderr,
                           "[rust-unified] expectEvents: command doc mismatch "
                           "for '%s'\n",
                           ev->command_name);
                  return false;
               }
            }
         }
      }
   }
   return true;
}

/* -----------------------------------------------------------------------
 * Outcome verification
 * ----------------------------------------------------------------------- */

static bool
check_outcome (const bson_t *outcome_arr)
{
   if (!outcome_arr) {
      return true;
   }

   mongoc_client_t *client = test_framework_new_default_client ();
   bool pass = true;

   bson_iter_t iter;
   bson_iter_init (&iter, outcome_arr);

   while (bson_iter_next (&iter)) {
      if (!BSON_ITER_HOLDS_DOCUMENT (&iter)) continue;
      uint32_t el;
      const uint8_t *ed;
      bson_iter_document (&iter, &el, &ed);
      bson_t entry;
      bson_init_static (&entry, ed, el);

      bson_iter_t ei;
      const char *coll_name = NULL, *db_name = NULL;

      bson_iter_init_find (&ei, &entry, "collectionName");
      if (BSON_ITER_HOLDS_UTF8 (&ei)) coll_name = bson_iter_utf8 (&ei, NULL);

      bson_iter_init_find (&ei, &entry, "databaseName");
      if (BSON_ITER_HOLDS_UTF8 (&ei)) db_name = bson_iter_utf8 (&ei, NULL);

      if (!coll_name || !db_name) continue;

      /* Get expected documents array. */
      bson_t expected_docs;
      bool has_expected = false;
      bson_iter_init_find (&ei, &entry, "documents");
      if (BSON_ITER_HOLDS_ARRAY (&ei)) {
         uint32_t dl;
         const uint8_t *dd;
         bson_iter_array (&ei, &dl, &dd);
         bson_init_static (&expected_docs, dd, dl);
         has_expected = true;
      }

      /* Query actual collection sorted by _id. */
      mongoc_collection_t *coll =
         mongoc_client_get_collection (client, db_name, coll_name);
      bson_t sort;
      bson_init (&sort);
      BSON_APPEND_INT32 (&sort, "_id", 1);
      mongoc_find_and_modify_opts_t *opts = NULL;

      bson_t query;
      bson_init (&query);
      mongoc_cursor_t *cursor = mongoc_collection_find_with_opts (
         coll, &query, tmp_bson ("{'sort': {'_id': 1}}"), NULL);
      bson_destroy (&query);
      bson_destroy (&sort);

      int n_actual = 0;
      const bson_t *actual_doc;

      bson_iter_t expected_iter;
      if (has_expected) {
         bson_iter_init (&expected_iter, &expected_docs);
      }

      while (mongoc_cursor_next (cursor, &actual_doc)) {
         if (has_expected) {
            if (!bson_iter_next (&expected_iter)) {
               fprintf (
                  stderr,
                  "[rust-unified] outcome: more actual docs than expected\n");
               pass = false;
               break;
            }
            if (!BSON_ITER_HOLDS_DOCUMENT (&expected_iter)) {
               n_actual++;
               continue;
            }
            uint32_t edl;
            const uint8_t *edd;
            bson_iter_document (&expected_iter, &edl, &edd);
            bson_t expected_doc;
            bson_init_static (&expected_doc, edd, edl);

            /* Use bson_equal for exact comparison; match_json misinterprets
             * literal dotted keys (e.g. "a.b") as nested path expressions. */
            if (!bson_equal (actual_doc, &expected_doc)) {
               char *aj = bson_as_relaxed_extended_json (actual_doc, NULL);
               char *ej = bson_as_relaxed_extended_json (&expected_doc, NULL);
               fprintf (stderr,
                        "[rust-unified] outcome: doc %d mismatch\n"
                        "  actual  : %s\n"
                        "  expected: %s\n",
                        n_actual,
                        aj,
                        ej);
               bson_free (aj);
               bson_free (ej);
               pass = false;
               break;
            }
         }
         n_actual++;
      }

      /* Check cursor error. */
      bson_error_t cerr;
      if (mongoc_cursor_error (cursor, &cerr)) {
         fprintf (
            stderr, "[rust-unified] outcome cursor error: %s\n", cerr.message);
         pass = false;
      }

      /* Check that we consumed all expected docs. */
      if (pass && has_expected && bson_iter_next (&expected_iter)) {
         fprintf (stderr,
                  "[rust-unified] outcome: fewer actual docs than expected\n");
         pass = false;
      }

      mongoc_cursor_destroy (cursor);
      mongoc_collection_destroy (coll);

      if (!pass) break;
   }

   mongoc_client_destroy (client);
   return pass;
}

/* -----------------------------------------------------------------------
 * Per-test-file runner (callback for install_json_test_suite)
 * ----------------------------------------------------------------------- */

static void
run_rust_unified_test_file (void *arg)
{
   bson_t *file = (bson_t *) arg;

   /* --- Schema version check --- */
   bson_iter_t iter;
   if (bson_iter_init_find (&iter, file, "schemaVersion") &&
       BSON_ITER_HOLDS_UTF8 (&iter)) {
      const char *sv = bson_iter_utf8 (&iter, NULL);
      int major, minor, patch;
      if (parse_semver (sv, &major, &minor, &patch)) {
         if (major > 1) {
            /* Cannot handle schema versions > 1 */
            fprintf (stderr,
                     "[rust-unified] Skipping: schemaVersion %s unsupported\n",
                     sv);
            return;
         }
      }
   }

   /* --- File-level runOnRequirements --- */
   bson_t file_req_arr;
   bool has_file_req = false;
   if (bson_iter_init_find (&iter, file, "runOnRequirements") &&
       BSON_ITER_HOLDS_ARRAY (&iter)) {
      uint32_t rl;
      const uint8_t *rd;
      bson_iter_array (&iter, &rl, &rd);
      bson_init_static (&file_req_arr, rd, rl);
      has_file_req = true;
   }
   if (has_file_req) {
      char *skip_reason = NULL;
      if (!check_run_on_requirements (&file_req_arr, &skip_reason)) {
         fprintf (stderr,
                  "[rust-unified] Skipping file: %s\n",
                  skip_reason);
         bson_free (skip_reason);
         return;
      }
   }

   /* --- File-level createEntities template --- */
   bson_t create_entities_arr;
   bool has_create_entities = false;
   if (bson_iter_init_find (&iter, file, "createEntities") &&
       BSON_ITER_HOLDS_ARRAY (&iter)) {
      uint32_t cel;
      const uint8_t *ced;
      bson_iter_array (&iter, &cel, &ced);
      bson_init_static (&create_entities_arr, ced, cel);
      has_create_entities = true;
   }

   /* --- File-level initialData --- */
   bson_t initial_data_arr;
   bool has_initial_data = false;
   if (bson_iter_init_find (&iter, file, "initialData") &&
       BSON_ITER_HOLDS_ARRAY (&iter)) {
      uint32_t idl;
      const uint8_t *idd;
      bson_iter_array (&iter, &idl, &idd);
      bson_init_static (&initial_data_arr, idd, idl);
      has_initial_data = true;
   }

   /* --- Iterate tests --- */
   if (!bson_iter_init_find (&iter, file, "tests") ||
       !BSON_ITER_HOLDS_ARRAY (&iter)) {
      return;
   }
   uint32_t tal;
   const uint8_t *tad;
   bson_iter_array (&iter, &tal, &tad);
   bson_t tests_arr;
   bson_init_static (&tests_arr, tad, tal);

   bson_iter_t ti;
   bson_iter_init (&ti, &tests_arr);

   while (bson_iter_next (&ti)) {
      if (!BSON_ITER_HOLDS_DOCUMENT (&ti)) continue;
      uint32_t tl;
      const uint8_t *td;
      bson_iter_document (&ti, &tl, &td);
      bson_t test;
      bson_init_static (&test, td, tl);

      /* Test description */
      const char *desc = "(no description)";
      bson_iter_t di;
      if (bson_iter_init_find (&di, &test, "description") &&
          BSON_ITER_HOLDS_UTF8 (&di)) {
         desc = bson_iter_utf8 (&di, NULL);
      }

      /* skipReason */
      if (bson_iter_init_find (&di, &test, "skipReason") &&
          BSON_ITER_HOLDS_UTF8 (&di)) {
         fprintf (stderr,
                  "[rust-unified] SKIP '%s': %s\n",
                  desc,
                  bson_iter_utf8 (&di, NULL));
         continue;
      }

      /* test-level runOnRequirements */
      bson_t test_req_arr;
      bool has_test_req = false;
      if (bson_iter_init_find (&di, &test, "runOnRequirements") &&
          BSON_ITER_HOLDS_ARRAY (&di)) {
         uint32_t rl;
         const uint8_t *rd;
         bson_iter_array (&di, &rl, &rd);
         bson_init_static (&test_req_arr, rd, rl);
         has_test_req = true;
      }
      if (has_test_req) {
         char *skip_reason = NULL;
         if (!check_run_on_requirements (&test_req_arr, &skip_reason)) {
            fprintf (stderr,
                     "[rust-unified] SKIP '%s': %s\n",
                     desc,
                     skip_reason);
            bson_free (skip_reason);
            continue;
         }
      }

      /* Load initial data fresh for each test */
      if (has_initial_data) {
         load_initial_data (&initial_data_arr);
      }

      /* Create entities fresh for each test */
      entity_map_t map;
      memset (&map, 0, sizeof (map));
      if (has_create_entities) {
         char *skip_reason = NULL;
         if (!create_entities (&map, &create_entities_arr, &skip_reason)) {
            fprintf (
               stderr, "[rust-unified] SKIP '%s': %s\n", desc, skip_reason);
            bson_free (skip_reason);
            entity_map_destroy (&map);
            continue;
         }
      }

      /* Run operations */
      bool test_failed = false;
      bool test_skipped = false;
      char *skip_reason = NULL;
      failpoint_list_t fps;
      failpoint_list_init (&fps);

      if (bson_iter_init_find (&di, &test, "operations") &&
          BSON_ITER_HOLDS_ARRAY (&di)) {
         uint32_t ol;
         const uint8_t *od;
         bson_iter_array (&di, &ol, &od);
         bson_t ops_arr;
         bson_init_static (&ops_arr, od, ol);

         bson_iter_t oi;
         bson_iter_init (&oi, &ops_arr);

         while (bson_iter_next (&oi)) {
            if (!BSON_ITER_HOLDS_DOCUMENT (&oi)) continue;
            uint32_t opl;
            const uint8_t *opd;
            bson_iter_document (&oi, &opl, &opd);
            bson_t op;
            bson_init_static (&op, opd, opl);

            char *op_skip = NULL;
            op_status_t status = dispatch_operation (&map, &op, &fps, &op_skip);

            if (status == OP_SKIP) {
               test_skipped = true;
               skip_reason = op_skip;
               break;
            } else if (status == OP_FAIL) {
               test_failed = true;
               bson_free (op_skip);
               break;
            }
            bson_free (op_skip);
         }
      }

      /* Disable any failpoints activated during this test. */
      failpoint_list_disable_all (&fps, &map);

      if (test_skipped) {
         fprintf (
            stderr, "[rust-unified] SKIP '%s': %s\n", desc, skip_reason);
         bson_free (skip_reason);
         entity_map_destroy (&map);
         continue;
      }

      if (!test_failed) {
         /* Check expectEvents */
         if (bson_iter_init_find (&di, &test, "expectEvents") &&
             BSON_ITER_HOLDS_ARRAY (&di)) {
            uint32_t eel;
            const uint8_t *eed;
            bson_iter_array (&di, &eel, &eed);
            bson_t expect_events_arr;
            bson_init_static (&expect_events_arr, eed, eel);
            if (!check_expect_events (&expect_events_arr, &map)) {
               test_failed = true;
            }
         }
      }

      if (!test_failed) {
         /* Check outcome */
         bson_t outcome_arr;
         bool has_outcome = false;
         if (bson_iter_init_find (&di, &test, "outcome") &&
             BSON_ITER_HOLDS_ARRAY (&di)) {
            uint32_t ol;
            const uint8_t *od;
            bson_iter_array (&di, &ol, &od);
            bson_init_static (&outcome_arr, od, ol);
            has_outcome = true;
         }

         if (has_outcome && !check_outcome (&outcome_arr)) {
            test_failed = true;
         }
      }

      entity_map_destroy (&map);

      if (test_failed) {
         /* Use BSON_ASSERT to fail the TestSuite test. */
         fprintf (stderr, "[rust-unified] FAIL '%s'\n", desc);
         BSON_ASSERT (false);
      } else {
         fprintf (stderr, "[rust-unified] PASS '%s'\n", desc);
      }
   }
}

